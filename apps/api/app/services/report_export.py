"""Ranking and audit exports: PDF (reportlab), Excel (openpyxl) and CSV."""
from __future__ import annotations

import io
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

GREEN = "316C4E"
CRIMSON = "B53043"
REC_FILL: dict[str, str] = {
    "Shortlist": "E7F0EA",
    "Consider": "FBF0DC",
    "Hold": "E6EDF5",
    "Reject": "F8E6E9",
}

# key, header, width
RANKING_COLS: list[tuple[str, str, int]] = [
    ("rank", "Rank", 7),
    ("vacancy", "Vacancy", 30),
    ("full_name", "Candidate", 24),
    ("overall_score", "Score", 8),
    ("total_years", "Total yrs", 9),
    ("relevant_years", "Relevant yrs", 11),
    ("qualification_match", "Qual. match %", 12),
    ("skills_match", "Skills match %", 12),
    ("ai_recommendation", "AI recommendation", 16),
    ("final_recommendation", "Final recommendation", 18),
    ("override_reason", "Override reason", 30),
    ("status", "Status", 12),
    ("key_strengths", "Key strengths", 50),
    ("key_gaps", "Key gaps", 50),
    ("justification", "Justification", 60),
]

PDF_COLS: list[tuple[str, str, int]] = [
    ("rank", "#", 22),
    ("full_name", "Candidate", 120),
    ("overall_score", "Score", 36),
    ("relevant_years", "Rel. yrs", 40),
    ("skills_match", "Skills %", 42),
    ("final_recommendation", "Recommendation", 80),
    ("key_strengths", "Key strengths", 215),
    ("key_gaps", "Key gaps", 215),
]


def csv_quote(v: Any) -> str:
    if v is None:
        s = ""
    elif isinstance(v, (dict, list)):
        import json

        s = json.dumps(v)
    else:
        s = str(v)
    if any(c in s for c in ('"', ",", "\n")):
        return '"' + s.replace('"', '""') + '"'
    return s


def ranking_csv(data: list[dict[str, Any]], cols: list[tuple[str, str, int]] = RANKING_COLS) -> str:
    lines = [",".join(c[1] for c in cols)]
    for r in data:
        lines.append(",".join(csv_quote(r.get(c[0])) for c in cols))
    return "\ufeff" + "\n".join(lines)


def ranking_xlsx(data: list[dict[str, Any]], email: str, cols: list[tuple[str, str, int]] = RANKING_COLS) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    wb = Workbook()
    ws = wb.active
    ws.title = "Ranking"
    ws.freeze_panes = "A2"

    for i, (_, header, width) in enumerate(cols, start=1):
        ws.column_dimensions[get_column_letter(i)].width = width
        cell = ws.cell(row=1, column=i, value=header)
        cell.font = Font(bold=True, color="FFFFFFFF")
        cell.fill = PatternFill(fill_type="solid", start_color="FF" + GREEN, end_color="FF" + GREEN)

    for r in data:
        ws.append([r.get(c[0]) for c in cols])

    ws.auto_filter.ref = f"A1:{get_column_letter(len(cols))}{max(len(data) + 1, 1)}"
    rec_idx = next((i for i, c in enumerate(cols, start=1) if c[0] == "final_recommendation"), None)
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
        if rec_idx:
            rec = row[rec_idx - 1].value
            if rec in REC_FILL:
                row[rec_idx - 1].fill = PatternFill(
                    fill_type="solid", start_color="FF" + REC_FILL[rec], end_color="FF" + REC_FILL[rec]
                )

    about = wb.create_sheet("About")
    for row in [
        ["ECEWS TalentScreen export"],
        ["Generated", datetime.now(timezone.utc).isoformat()],
        ["Generated by", email],
        ["Rows", len(data)],
        [],
        ["Recommendations are AI-assisted decision support. Final hiring decisions are made by authorised ECEWS staff."],
    ]:
        about.append(row)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _logo_path() -> Path:
    return Path(__file__).resolve().parents[2] / "assets" / "ecews-logo.png"


def ranking_pdf(data: list[dict[str, Any]], email: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=landscape(A4),
        leftMargin=10 * mm,
        rightMargin=10 * mm,
        topMargin=10 * mm,
        bottomMargin=12 * mm,
        title="TalentScreen ranking",
        author="ECEWS",
    )
    styles = {
        "title": ParagraphStyle("title", fontName="Helvetica-Bold", fontSize=16, textColor=colors.HexColor("#" + GREEN)),
        "meta": ParagraphStyle("meta", fontName="Helvetica", fontSize=9, textColor=colors.HexColor("#555555")),
        "vacancy": ParagraphStyle("vacancy", fontName="Helvetica-Bold", fontSize=11, textColor=colors.HexColor("#" + CRIMSON)),
        "th": ParagraphStyle("th", fontName="Helvetica-Bold", fontSize=8, textColor=colors.white),
        "td": ParagraphStyle("td", fontName="Helvetica", fontSize=7.5, textColor=colors.HexColor("#222222")),
        "foot": ParagraphStyle("foot", fontName="Helvetica-Oblique", fontSize=7.5, textColor=colors.HexColor("#777777")),
    }

    story: list[Any] = []
    logo = _logo_path()
    if logo.exists():
        try:
            from reportlab.platypus import Image

            img = Image(str(logo), height=14 * mm, width=14 * mm)
            story.append(img)
        except Exception:
            pass
    story.append(Paragraph("Candidate ranking", styles["title"]))
    story.append(Paragraph(
        f"Generated {datetime.now(timezone.utc).strftime('%d/%m/%Y, %H:%M:%S')} UTC by {email}",
        styles["meta"],
    ))
    story.append(Spacer(1, 8))

    header = [Paragraph(h, styles["th"]) for _, h, _ in PDF_COLS]
    widths = [w for _, _, w in PDF_COLS]

    if not data:
        story.append(Paragraph("No completed evaluations for this selection.", styles["td"]))
    else:
        current = None
        rows: list[list[Any]] = []
        styles_cmds: list[tuple] = []

        def flush() -> None:
            if not rows:
                return
            tbl = Table([header] + rows, colWidths=widths, repeatRows=1)
            cmds = [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#" + GREEN)),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#DDDDDD")),
                ("LEFTPADDING", (0, 0), (-1, -1), 3),
                ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
            ]
            cmds.extend(styles_cmds)
            tbl.setStyle(TableStyle(cmds))
            story.append(tbl)
            story.append(Spacer(1, 8))

        for r in data:
            if r.get("vacancy") != current:
                flush()
                current = r.get("vacancy")
                rows = []
                styles_cmds = []
                story.append(Spacer(1, 4))
                story.append(Paragraph(f"{current}  ({r.get('ref_code') or ''})", styles["vacancy"]))
                story.append(Spacer(1, 3))
            rows.append([Paragraph(str(r.get(k) if r.get(k) is not None else ""), styles["td"]) for k, _, _ in PDF_COLS])
            rec = r.get("final_recommendation")
            if rec in REC_FILL:
                idx = next(i for i, c in enumerate(PDF_COLS) if c[0] == "final_recommendation")
                row_no = len(rows)  # header row is 0
                styles_cmds.append((
                    "BACKGROUND", (idx, row_no), (idx, row_no),
                    colors.HexColor("#" + REC_FILL[rec]),
                ))
        flush()

    story.append(Spacer(1, 10))
    story.append(Paragraph(
        "AI-assisted decision support. Final hiring decisions are made by authorised ECEWS staff.",
        styles["foot"],
    ))
    doc.build(story)
    return buf.getvalue()


AUDIT_COLS = ["id", "at", "actor_email", "actor_role", "action", "entity_type", "entity_id", "details", "ip", "hash"]


def audit_csv(rows: list[dict[str, Any]]) -> str:
    lines = [",".join(AUDIT_COLS)]
    for r in rows:
        values = []
        for c in AUDIT_COLS:
            v = r.get(c)
            if c == "at" and v is not None:
                v = v.isoformat().replace("+00:00", "Z") if hasattr(v, "isoformat") else str(v)
            values.append(csv_quote(v))
        lines.append(",".join(values))
    return "\ufeff" + "\n".join(lines)
